/// v2：老 Android 系统根证书库缺失的新根（Mozilla CA 列表中 2016 年后签发
/// 的根，来源 https://curl.se/ca/cacert.pem）。
///
/// 实测（CI 模拟器 Android 11）：AGE（www.agedm.io）证书链到
/// 「SSL.com TLS RSA Root CA 2022」，系统库里没有 → Dart HttpClient 握手
/// 失败（日志里只显示「网络异常」），App 内搜索为空。Android ≤13 的
/// 存量手机同样受影响；这里在系统库之外追加这些根，不放宽任何校验。
abstract final class ExtraTrustedRoots {
  static SecurityContext? _context;

  /// 系统根 + 追加根的 SecurityContext（进程内共享）。
  static SecurityContext get context => _context ??= _build();

  /// 新建一个用该信任库的 HttpClient。
  static HttpClient newHttpClient() => HttpClient(context: context);

  static SecurityContext _build() {
    final ctx = SecurityContext(withTrustedRoots: true);
    final re = RegExp(
        r'-----BEGIN CERTIFICATE-----[\s\S]*?-----END CERTIFICATE-----');
    for (final m in re.allMatches(pem)) {
      try {
        ctx.setTrustedCertificatesBytes(utf8.encode(m.group(0)!));
      } catch (_) {
        // 与系统库重复/个别解析失败：跳过该根即可。
      }
    }
    return ctx;
  }

